"""
contract_realization.py

Independent realization of the reference contract SatPsi.

This generator is deliberately SEPARATE from scripts/generate_dafny_variants.py
(the implementation-lever realization). It is authored directly from the meaning
of the contract atoms

    PC = ORIGINAL_PUBLIC_CONTRACT_SURFACE
    IB = ORIGINAL_IMPLEMENTATION_BEHAVIOR

and NOT by feeding betaSet(T) into the implementation-lever renderer.

Contract-atom semantics (retained-set convention):
  * Keep PC  => the public API preserves its ORIGINAL acceptance surface:
                Trend accepts span != 0, Percent accepts whole > 0.
    Delete PC => replace the original public-contract surface with the declared
                repaired surface: Trend is STRENGTHENED from != 0 to > 0 (its
                input domain shrinks) while Percent is WEAKENED from > 0 to != 0
                (its input domain grows). The block is therefore a
                mixed-direction transformation, not a relaxation -- which is why
                Psi-deletion monotonicity fails in the closed-world scope.
  * Keep IB  => Trend realizes the ORIGINAL behavior: a direct delegation.
    Delete IB => Trend realizes the guarded behavior.

Surface differences from the implementation realization (so that agreement is a
conformance audit, not a hash-identity tautology):
  * preconditions and guards are expressed through NAMED contract predicates
    (PositiveSpan / NonzeroSpan / PositiveWhole / NonzeroWhole), not inline
    relational expressions;
  * the file is organized around contract atoms (public-surface block, then
    implementation-behavior block).

The intended semantics correspond to the implementation realization, so for a
correct pair of encodings SatPhi(betaSet(T)) and SatPsi(T) agree. A realization
defect that changes the measured feasibility outcome on one side but not the
corresponding outcome on the other side is detected as a ResidualFaithfulness
failure. Correlated defects (the same conceptual error on both sides) and defects
that preserve all measured Boolean outcomes may remain undetected. This is a
cross-realization conformance check, not an independent semantic theorem.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m3lib as m3

PRED_DEFS = {
    "PositiveSpan": "predicate PositiveSpan(s: int)  { s > 0 }",
    "NonzeroSpan": "predicate NonzeroSpan(s: int)   { s != 0 }",
    "PositiveWhole": "predicate PositiveWhole(w: int) { w > 0 }",
    "NonzeroWhole": "predicate NonzeroWhole(w: int)  { w != 0 }",
}
PRED_ORDER = ["PositiveSpan", "NonzeroSpan", "PositiveWhole", "NonzeroWhole"]


def render_contract_program(retained_atoms, scope):
    """Dafny source for the reference-contract realization of retained atom set T."""
    pc_kept = m3.PC in retained_atoms
    ib_kept = m3.IB in retained_atoms

    # Public contract surface realization (named predicates).
    span_pred = "NonzeroSpan" if pc_kept else "PositiveSpan"
    whole_pred = "PositiveWhole" if pc_kept else "NonzeroWhole"

    # Implementation behavior realization.
    if ib_kept:
        trend_body = "{ r := Percent(delta, span); }"
    else:
        trend_body = (
            "{\n"
            "  if PositiveSpan(span) { r := Percent(delta, span); }\n"
            "  else                  { r := 0; }\n"
            "}"
        )

    needed = {span_pred, whole_pred}
    if not ib_kept:
        needed.add("PositiveSpan")
    preds = "\n".join(PRED_DEFS[p] for p in PRED_ORDER if p in needed)

    header = (
        "// AUTO-GENERATED by scripts/contract_realization.py -- do not edit.\n"
        "// REFERENCE-CONTRACT realization (independent from the lever renderer).\n"
        f"// scope                 = {scope}\n"
        f"// retained contract atoms T = {sorted(m3.ATOM_CODE[a] for a in retained_atoms)}\n"
        f"// public contract surface   = {'ORIGINAL' if pc_kept else 'altered/repaired (Trend !=0=>>0 strengthened, Percent >0=>!=0 weakened)'}\n"
        f"// implementation behavior   = {'ORIGINAL (direct)' if ib_kept else 'guarded'}\n"
    )

    parts = [header]
    parts.append("// -- public contract surface predicates --\n" + preds + "\n")
    parts.append(
        "method Percent(part: int, whole: int) returns (r: int)\n"
        f"  requires {whole_pred}(whole)\n"
        "  ensures  r == part * 100 / whole\n"
        "{ r := part * 100 / whole; }\n"
    )
    parts.append(
        "method Ratio(x: int) returns (r: int)\n"
        "  ensures r == x * 100 / 4\n"
        "{ r := Percent(x, 4); }\n"
    )
    parts.append(
        "// -- implementation behavior realization --\n"
        "method Trend(delta: int, span: int) returns (r: int)\n"
        f"  requires {span_pred}(span)\n"
        f"{trend_body}\n"
    )
    if scope == "closed_world":
        parts.append(
            "method TrendUserOK(d: int, s: int) returns (r: int)\n"
            "  requires s > 0\n"
            "{ r := Trend(d, s); }\n"
        )
        parts.append(
            "method TrendUserNonzero(d: int, s: int) returns (r: int)\n"
            "  requires s != 0\n"
            "{ r := Trend(d, s); }\n"
        )
    return "\n".join(parts)
