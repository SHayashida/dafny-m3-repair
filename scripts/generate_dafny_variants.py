"""
generate_dafny_variants.py

Materialize the finite lattice of Dafny source variants under the retained-set
convention, for both validation scopes.

Implementation residuals: all 8 retained lever sets K subseteq LambdaI.
Contract residuals:        all 4 retained atom sets  T subseteq I, whose retained
                           lever set is betaSet(T) (independently materialized).

A *deleted* lever applies its edit:
  delete T -> C1: Trend.requires  span != 0  ==>  span > 0
  delete P -> C2: Percent.requires whole > 0 ==>  whole != 0
  delete D -> C3: Trend body direct call     ==>  guarded implementation

Local scope methods:        Percent, Ratio, Trend
Closed-world scope methods: Percent, Ratio, Trend, TrendUserOK, TrendUserNonzero
"""

import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m3lib as m3
import contract_realization

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "m3" / "generated"


def render_program(retained_levers, scope):
    """Return Dafny source text for a variant with the given retained lever set."""
    apply_c1 = m3.T not in retained_levers   # delete T => C1
    apply_c2 = m3.P not in retained_levers   # delete P => C2
    apply_c3 = m3.D not in retained_levers   # delete D => C3

    percent_req = "whole != 0" if apply_c2 else "whole > 0"
    trend_req = "span > 0" if apply_c1 else "span != 0"

    if apply_c3:
        trend_body = (
            "{\n"
            "  if span > 0 { r := Percent(delta, span); }\n"
            "  else        { r := 0; }\n"
            "}"
        )
    else:
        trend_body = "{ r := Percent(delta, span); }"

    header = (
        "// AUTO-GENERATED by scripts/generate_dafny_variants.py -- do not edit.\n"
        f"// scope              = {scope}\n"
        f"// retained levers K  = {sorted(m3.LEVER_CODE[x] for x in retained_levers)}\n"
        f"// applied edits      = "
        f"{[e for e, on in [('C1', apply_c1), ('C2', apply_c2), ('C3', apply_c3)] if on] or ['none (base)']}\n"
    )

    body = []
    body.append(header)
    body.append(
        "method Percent(part: int, whole: int) returns (r: int)\n"
        f"  requires {percent_req}\n"
        "  ensures  r == part * 100 / whole\n"
        "{ r := part * 100 / whole; }\n"
    )
    body.append(
        "method Ratio(x: int) returns (r: int)\n"
        "  ensures r == x * 100 / 4\n"
        "{ r := Percent(x, 4); }\n"
    )
    body.append(
        "method Trend(delta: int, span: int) returns (r: int)\n"
        f"  requires {trend_req}\n"
        f"{trend_body}\n"
    )
    if scope == "closed_world":
        body.append(
            "method TrendUserOK(d: int, s: int) returns (r: int)\n"
            "  requires s > 0\n"
            "{ r := Trend(d, s); }\n"
        )
        body.append(
            "method TrendUserNonzero(d: int, s: int) returns (r: int)\n"
            "  requires s != 0\n"
            "{ r := Trend(d, s); }\n"
        )
    return "\n".join(body)


def variant_records():
    """Enumerate every source variant to materialize.

    Returns list of dicts with kind (impl|contract), scope, retained levers,
    (for contract) retained atoms, and target path.
    """
    records = []
    for scope, sub in (("local", "local"), ("closed_world", "closed")):
        # implementation residuals: 8 retained lever sets K
        for k in m3.powerset(m3.LAMBDA_I):
            code = m3.code_for_levers(k)
            path = GEN / sub / f"impl_{code}.dfy"
            records.append({
                "kind": "impl",
                "scope": scope,
                "retained_levers": sorted(m3.sorted_levers(k)),
                "retained_levers_set": k,
                "path": path,
            })
        # contract residuals: 4 retained atom sets T; retained levers = betaSet(T)
        for t in m3.powerset(m3.I):
            bset = m3.beta_set(t)
            code = m3.code_for_atoms(t)
            path = GEN / sub / f"contract_{code}.dfy"
            records.append({
                "kind": "contract",
                "scope": scope,
                "retained_atoms": m3.sorted_atoms(t),
                "retained_atoms_set": t,
                "retained_levers": m3.sorted_levers(bset),
                "retained_levers_set": bset,
                "path": path,
            })
    return records


def main():
    (GEN / "local").mkdir(parents=True, exist_ok=True)
    (GEN / "closed").mkdir(parents=True, exist_ok=True)
    written = 0
    for rec in variant_records():
        if rec["kind"] == "impl":
            # implementation-lever realization
            text = render_program(rec["retained_levers_set"], rec["scope"])
        else:
            # INDEPENDENT reference-contract realization, authored from the
            # contract-atom meaning (not from betaSet(T) via render_program).
            text = contract_realization.render_contract_program(
                rec["retained_atoms_set"], rec["scope"])
        rec["path"].write_text(text, encoding="utf-8", newline="\n")
        written += 1
    print(f"generated {written} Dafny source variants under {GEN}")


if __name__ == "__main__":
    main()
